import fs from 'node:fs/promises';
import {VERSION,RELEASE_TAG} from '../src/version.mjs';
import path from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {fileURLToPath} from 'node:url';
const exec=promisify(execFile),root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
if(!process.argv[2])throw Error('请指定候选包目录');
const pack=path.resolve(process.argv[2]),dest=path.join(root,'verification/release',`package-check-${path.basename(pack)}`);
await fs.mkdir(dest,{recursive:true});
const names=[`CodexProjectColors-${RELEASE_TAG}-source`,`CodexProjectColors-${RELEASE_TAG}-macos-arm64`];
for(const name of names)await exec('/usr/bin/ditto',['-x','-k',path.join(pack,name+'.zip'),dest]);
const source=path.join(dest,names[0]),app=path.join(dest,names[1],'Codex Project Colors.app');
const tests=await exec('/bin/zsh',['-c','node --test --test-reporter=tap src/*.test.mjs demo/core/*.test.mjs'],{cwd:source,maxBuffer:1000000});
await fs.writeFile(path.join(dest,'source-tests.txt'),tests.stdout);
const counts=Object.fromEntries([...tests.stdout.matchAll(/^# (tests|pass|fail|cancelled|skipped) (\d+)$/gm)].map(match=>[match[1],Number(match[2])]));
const localTests=await exec('/bin/zsh',['-c','node --test --test-reporter=tap src/*.test.mjs demo/core/*.test.mjs'],{cwd:root,maxBuffer:1000000});
const expected=Number(localTests.stdout.match(/^# tests (\d+)$/m)?.[1]);
if(!expected||counts.tests!==expected||counts.fail!==0||counts.pass!==expected)throw Error('独立源码测试数量或结果异常');
await exec('/usr/bin/codesign',['--verify','--strict',app]);
const version=(await exec(path.join(app,'Contents/Resources/node'),['--version'])).stdout.trim();
const appVersion=(await exec('/usr/libexec/PlistBuddy',['-c','Print CFBundleShortVersionString',path.join(app,'Contents/Info.plist')])).stdout.trim();
const status=JSON.parse((await exec(path.join(app,'Contents/Resources/node'),[path.join(app,'Contents/Resources/tool/src/cli.mjs'),'status','--data-dir',path.join(dest,'fresh-data')])).stdout);
const checksums=await exec('/usr/bin/shasum',['-a','256','-c','SHA256SUMS.txt'],{cwd:pack});
const result={passed:status.running===false&&version==='v24.21.0'&&appVersion===VERSION,packageDirectory:pack,sourceTests:counts,runtime:version,appVersion,signatureIntegrity:'passed (ad hoc only)',freshCLI:status,checksums:checksums.stdout};
await fs.writeFile(path.join(root,`verification/release/${RELEASE_TAG}-package-check.json`),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));if(!result.passed)process.exitCode=1;
